/**
 * The SQLite and Postgres schemas must describe the same database: same tables, columns,
 * nullability, defaults, TypeScript data types, keys, indexes, foreign keys and checks.
 */
import { type Column, getTableName, is } from 'drizzle-orm';
import { getTableConfig as getPgTableConfig, PgTable } from 'drizzle-orm/pg-core';
import { getTableConfig as getSqliteTableConfig, SQLiteTable } from 'drizzle-orm/sqlite-core';
import { describe, expect, it } from 'vitest';
import { pgSchema, sqliteSchema } from '../src';

type TableConfig = ReturnType<typeof getSqliteTableConfig> | ReturnType<typeof getPgTableConfig>;

function describeColumn(c: Column) {
  return {
    name: c.name,
    dataType: c.dataType,
    notNull: c.notNull,
    // Identity/autoincrement ids are generated by the database in both dialects.
    hasDefault: c.hasDefault || (c.primary && c.name === 'id'),
    primary: c.primary,
    enumValues: c.enumValues ?? null,
  };
}

function describeTable(config: TableConfig) {
  return {
    name: config.name,
    columns: config.columns.map((c) => describeColumn(c as Column)).sort((a, b) => a.name.localeCompare(b.name)),
    primaryKeys: config.primaryKeys.map((pk) => ({
      name: pk.getName(),
      columns: pk.columns.map((c) => c.name),
    })),
    indexes: config.indexes
      .map((i) => ({
        name: i.config.name,
        unique: i.config.unique,
        columns: i.config.columns.map((c) => (c as Column).name),
      }))
      .sort((a, b) => (a.name ?? '').localeCompare(b.name ?? '')),
    foreignKeys: config.foreignKeys
      .map((fk) => {
        const ref = fk.reference();
        return {
          columns: ref.columns.map((c) => c.name),
          foreignTable: getTableName(ref.foreignTable),
          foreignColumns: ref.foreignColumns.map((c) => c.name),
          onDelete: fk.onDelete ?? 'no action',
        };
      })
      .sort((a, b) => a.columns.join().localeCompare(b.columns.join())),
    checks: config.checks.map((c) => c.name).sort(),
  };
}

const sqliteTables = Object.values(sqliteSchema)
  .filter((v: unknown): v is SQLiteTable => is(v, SQLiteTable))
  .map((t) => describeTable(getSqliteTableConfig(t)));
const pgTables = Object.values(pgSchema)
  .filter((v: unknown): v is PgTable => is(v, PgTable))
  .map((t) => describeTable(getPgTableConfig(t)));

describe('schema parity (SQLite vs Postgres)', () => {
  it('defines the 16 spec tables plus sessions', () => {
    const names = sqliteTables.map((t) => t.name).sort();
    expect(names).toEqual([
      'app_settings',
      'audit_log',
      'chat_messages',
      'clubs',
      'draft_picks',
      'fixtures',
      'games',
      'match_events',
      'participants',
      'player_season_stats',
      'players',
      'queue_items',
      'season_teams',
      'seasons',
      'sessions',
      'standing_rows',
      'users',
    ]);
    expect(pgTables.map((t) => t.name).sort()).toEqual(names);
  });

  for (const table of sqliteTables) {
    it(`table ${table.name} matches`, () => {
      expect(pgTables.find((t) => t.name === table.name)).toEqual(table);
    });
  }
});
